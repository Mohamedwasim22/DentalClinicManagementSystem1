    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        

    int selectedRow = tblPatients.getSelectedRow();

    if (selectedRow == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a patient from the table!"
        );

        return;
    }

    try {

        int id = Integer.parseInt(
                tblPatients.getValueAt(selectedRow, 0).toString()
        );

        String fullName = jTextField1.getText().trim();
        int age = Integer.parseInt(jTextField3.getText().trim());
        String gender = jComboBox1.getSelectedItem().toString();
        String phone = jTextField2.getText().trim();
        String address = jTextField4.getText().trim();
        String email = jTextField5.getText().trim();

        Patient patient = new Patient(
                id,
                fullName,
                age,
                gender,
                phone,
                email,
                address,
                ""
        );

        PatientDAO patientDAO = new PatientDAO();

        boolean updated = patientDAO.updatePatient(patient);

        if (updated) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Updated Successfully!"
            );

            loadPatients();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Update Failed!"
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter a valid age!"
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed


    int selectedRow = tblPatients.getSelectedRow();

    if (selectedRow == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a patient from the table!"
        );

        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this patient?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    try {

        int id = Integer.parseInt(
                tblPatients.getValueAt(selectedRow, 0).toString()
        );

        PatientDAO patientDAO = new PatientDAO();

        boolean deleted = patientDAO.deletePatient(id);

        if (deleted) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Deleted Successfully!"
            );

            loadPatients();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Delete Failed!"
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }
        
    }//GEN-LAST:event_jButton5ActionPerformed

    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        String keyword = jTextField6.getText().trim();

PatientService patientService = new PatientService();

List<Patient> patients = patientService.searchPatients(keyword);

DefaultTableModel model = (DefaultTableModel) tblPatients.getModel();

model.setRowCount(0);

for (Patient patient : patients) {

    model.addRow(new Object[]{
        patient.getId(),
        patient.getFullName(),
        patient.getAge(),
        patient.getGender(),
        patient.getPhone(),
        patient.getEmail(),
        patient.getAddress(),
        patient.getRegisterDate()
    });
}

if (patients.isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "No patient found!"
    );
}
    }//GEN-LAST:event_jButton7ActionPerformed

