    private void tblPatientsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPatientsMouseClicked


    int selectedRow = tblPatients.getSelectedRow();

    if (selectedRow >= 0) {

        DefaultTableModel model =
                (DefaultTableModel) tblPatients.getModel();

        // Patient Name
        jTextField1.setText(
                model.getValueAt(selectedRow, 1).toString()
        );

        // Age
        jTextField3.setText(
                model.getValueAt(selectedRow, 2).toString()
        );

        // Gender
        jComboBox1.setSelectedItem(
                model.getValueAt(selectedRow, 3).toString()
        );

        // Phone
        jTextField2.setText(
                model.getValueAt(selectedRow, 4).toString()
        );

        // Email
        jTextField5.setText(
                model.getValueAt(selectedRow, 5).toString()
        );

        // Address
        jTextField4.setText(
                model.getValueAt(selectedRow, 6).toString()
        );
    }

    }//GEN-LAST:event_tblPatientsMouseClicked


